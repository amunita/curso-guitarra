_svg_cache = {}


def chord_svgs(names):
    if not names:
        return ""
    html = ORIGINAL.read_text(encoding="utf-8")
    out = []
    for n in names:
        if n not in _svg_cache:
            m = re.search(
                rf'<div class="chord"><b>{re.escape(n)}</b><svg.*?</svg></div>', html, re.S
            )
            if not m:
                raise SystemExit(f"acorde sin diagrama en el original: {n}")
            _svg_cache[n] = m.group(0)
        out.append(_svg_cache[n])
    return '<div class="chords">' + "".join(out) + "</div>"


