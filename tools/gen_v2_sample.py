def render():
    parts = []
    for i, day in enumerate(DAYS, start=1):
        week = 1 if i <= 7 else 2
        dow = i - (week - 1) * 7
        mins = sum(e["min"] for e in day["ex"])
        assert mins == 30, f"día {i}: {mins} min"
        arts = []
        for n, e in enumerate(day["ex"], start=1):
            steps = "".join(f"<li>{s}</li>" for s in e["steps"])
            chords = chord_svgs(e["chords"])
            arts.append(
                f'<article class="exercise"><div class="exhead"><span>{n}</span><div>'
                f'<h3>{e["t"]}</h3><small>{e["min"]} min</small></div></div>\n'
                f'<div class="brief"><b>Qué harás:</b> {e["brief"]}</div>\n'
                f'<details><summary>Instrucciones paso a paso</summary><div class="detail"><ol>{steps}</ol>{chords}\n'
                f'<div class="watch"><b>Qué observar:</b> {e["watch"]}</div>'
                f'<div class="pass"><b>Criterio para pasar:</b> {e["crit"]}</div></div></details></article>'
            )
        parts.append(
            f'<section class="day" id="day-{i}" data-day="{i}" data-week="{week}">\n'
            f'<div class="dayhead"><div><div class="eyebrow">Semana {week} · Día {dow} · Día {i}/182 · v2</div>'
            f'<h2>{day["tema"]}</h2><p>{day["modo"]} · 30 min · foco: {day["foco"]}</p></div></div>\n'
            + "".join(arts)
            + "</section>"
        )
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"{OUT.name}: {len(DAYS)} días, {OUT.stat().st_size/1024:.0f} KB")


if __name__ == "__main__":
    render()
